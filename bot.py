# ===================== ОБРАБОТКА АНОНИМНОГО СООБЩЕНИЯ =====================
@dp.message(Form.waiting_message)
async def handle_anonymous_message(message: types.Message, state: FSMContext):
    user_id = message.from_user.id
    current_time = time.time()

    # Антиспам
    if user_id in last_message_time:
        time_passed = current_time - last_message_time[user_id]
        if time_passed < SPAM_LIMIT_SECONDS:
            remaining = int(SPAM_LIMIT_SECONDS - time_passed)
            await message.answer(f"Подождите еще <b>{remaining}</b> секунд.")
            return

    last_message_time[user_id] = current_time

    # Отправка администратору
    now = datetime.now(ZoneInfo("Europe/Minsk")).strftime("%d.%m.%Y %H:%M:%S")

    await bot.send_message(
        ADMIN_CHAT_ID,
        f"<b>Новое анонимное обращение</b>\n\n"
        f"Время: <b>{now}</b>\n\n"
        f"<b>Текст:</b>\n{message.text}"
    )

    await message.answer(
        "<b>✅ Сообщение успешно отправлено!</b>\n\n"
        "Спасибо за обращение.",
        reply_markup=main_keyboard
    )

    await state.clear()


